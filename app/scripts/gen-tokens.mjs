// Generates src/theme/tokens.ts from replica/design/tokens*.json.
// Run after any token change: npm run tokens
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const designDir = join(here, "..", "..", "replica", "design");
const dark = JSON.parse(readFileSync(join(designDir, "tokens.json"), "utf8"));
const light = JSON.parse(readFileSync(join(designDir, "tokens.light.json"), "utf8"));

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const colors = (c) => Object.fromEntries(Object.entries(c).map(([k, v]) => [camel(k), v]));
const strip = (o) =>
  Object.fromEntries(
    Object.entries(o)
      .filter(([k]) => !k.startsWith("_"))
      .map(([k, v]) => [camel(k), v && typeof v === "object" && !Array.isArray(v) ? strip(v) : v]),
  );

const out = {
  colors: { dark: colors(dark.color), light: colors(light.color) },
  type: strip(dark.type),
  space: dark.space,
  layout: strip(dark.layout),
  size: strip(dark.size),
  radius: strip(dark.radius),
  motion: strip(dark.motion),
  scrim: dark.shadow["sheet-scrim"],
};

const body = `// Generated by scripts/gen-tokens.mjs from replica/design/tokens*.json. Do not edit by hand.
export const tokens = ${JSON.stringify(out, null, 2)} as const;

export type ColorName = keyof typeof tokens.colors.dark;
export type Palette = Record<ColorName, string>;
export type TypeName = keyof typeof tokens.type;
`;
writeFileSync(join(here, "..", "src", "theme", "tokens.ts"), body);
console.log("wrote src/theme/tokens.ts");
