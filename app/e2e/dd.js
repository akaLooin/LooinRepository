const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  r.home = await p.getByText("자격증 시험").count();
  await p.getByRole("button", { name: /자격증 시험/ }).click();
  await p.waitForTimeout(400);
  await p.screenshot({ path: "S21.png" });
  r.list = await p.getByText(/^D-\d+$/).count();
  // reordering is covered by e2e/drag.js
  await p.getByRole("button", { name: "추가하기" }).click();
  await p.waitForTimeout(400);
  await p.getByRole("button", { name: "완료" }).click();
  r.nameErr = await p.getByText("이름을 입력해 주세요").count();
  await p.getByLabel("디데이 이름").fill("생일");
  await p.getByRole("radio", { name: "반복" }).click();
  await p.getByLabel("11월 20일", { exact: true }).last().click();
  await p.waitForTimeout(200);
  r.preview = await p.getByText(/오늘 기준 D-/).innerText();
  await p.screenshot({ path: "S21b.png" });
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(400);
  r.added = await p.getByText("생일").count();
  await p.getByRole("button", { name: /^생일, D/ }).click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "삭제" }).first().click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "삭제" }).last().click();
  await p.waitForTimeout(400);
  r.deleted = (await p.getByRole("button", { name: /^생일, D/ }).count()) === 0;
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
