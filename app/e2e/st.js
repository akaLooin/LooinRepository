const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  await p.goto("http://localhost:8765/settings/display", { waitUntil: "networkidle" });
  await p.waitForTimeout(400);
  await p.screenshot({ path: "S12d.png" });
  r.later = await p.getByText("준비 중").count();
  await p.getByRole("button", { name: "테마, 다크" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("radio", { name: "라이트" }).click();
  await p.getByRole("button", { name: "확인" }).click();
  await p.waitForTimeout(300);
  r.bgLight = await p.evaluate(() => getComputedStyle(document.querySelector("[aria-label='테마, 라이트']").closest("div[style*='background']") || document.body).backgroundColor);
  await p.getByRole("switch", { name: "달력에서 일요일부터 시작" }).click();
  await p.waitForTimeout(200);
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.waitForTimeout(600);
  const heads = await p.getByText(/^[일월화수목금토]$/).allInnerTexts();
  r.firstWeekday = heads[0];
  await p.screenshot({ path: "home-light.png" });
  await p.goto("http://localhost:8765/profile", { waitUntil: "networkidle" });
  await p.waitForTimeout(300);
  // the original's profile: each field on its own screen with 확인
  await p.getByRole("button", { name: /^이름, / }).click(); await p.waitForTimeout(300);
  await p.getByLabel("이름", { exact: true }).fill("루인2");
  await p.getByRole("button", { name: "확인" }).click(); await p.waitForTimeout(400);
  await p.getByRole("button", { name: /^자기소개, / }).click(); await p.waitForTimeout(300);
  await p.getByLabel("자기소개", { exact: true }).fill("오늘도 한 칸씩");
  await p.getByRole("button", { name: "확인" }).click(); await p.waitForTimeout(400);
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.waitForTimeout(500);
  r.nickname = await p.getByText("루인2").count();
  r.bio = await p.getByText("오늘도 한 칸씩").count();
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
