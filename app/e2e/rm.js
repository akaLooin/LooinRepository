const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  await p.getByLabel("11월 3일", { exact: true }).first().click(); // seed data lives on 3 Nov
  await p.getByLabel("관리 메뉴").click();
  await p.getByText("리마인더 관리").click();
  await p.waitForTimeout(500);
  r.empty = await p.getByText("아직 리마인더가 없어요", { exact: false }).count();
  await p.getByRole("button", { name: "추가하기" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("radio", { name: "21시" }).click();
  await p.getByRole("radio", { name: "30분" }).click();
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(400);
  r.added = await p.getByText("매일 21:30").count();
  r.webNotice = await p.getByText("알림은 폰 앱에서만 울려요").count();
  await p.screenshot({ path: "S22.png" });
  await p.getByRole("button", { name: "추가하기" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("radio", { name: "21시" }).click();
  await p.getByRole("radio", { name: "30분" }).click();
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(300);
  r.dupBlocked = await p.getByText("이미 있는 시간이에요").count();
  await p.getByRole("button", { name: "21:30 리마인더 삭제" }).click();
  await p.waitForTimeout(300);
  r.deleted = (await p.getByText("매일 21:30").count()) === 0;
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.waitForTimeout(400);
  // 시간 알림 is offered for today and later (not for past days, as in the original): add a to-do today
  await p.getByLabel("To Do에 할 일 추가").click();
  await p.getByLabel("할 일 입력").fill("책 30쪽 읽기");
  await p.getByLabel("할 일 입력").press("Enter");
  await p.getByLabel("할 일 입력").blur().catch(() => {});
  await p.waitForTimeout(400);
  await p.getByText("책 30쪽 읽기").click();
  await p.waitForTimeout(400);
  await p.getByText("시간 알림").click();
  await p.waitForTimeout(400);
  await p.getByRole("radio", { name: "20시" }).click();
  await p.getByRole("radio", { name: "15분" }).click();
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(400);
  r.alarmOnRow = await p.getByLabel("알림 20:15").count(); // clock + time under the title, as in the original
  await p.getByText("책 30쪽 읽기").click();
  await p.waitForTimeout(400);
  r.alarmShown = await p.getByText("시간 알림 · 20:15").count();
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
