const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  await p.getByRole("button", { name: "일기 쓰기" }).click();
  await p.waitForTimeout(500);
  await p.getByRole("button", { name: "오늘의 기분 고르기" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "🥳" }).click();
  await p.getByLabel("일기 내용").fill("루틴을 다 끝낸 날");
  await p.getByRole("button", { name: "배경색" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "배경 #F4EDE1" }).click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: "S09.png" });
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(400);
  r.homeRow = await p.getByText("루틴을 다 끝낸 날").count();
  await p.reload({ waitUntil: "networkidle" });
  await p.waitForTimeout(500);
  r.afterReload = await p.getByText("루틴을 다 끝낸 날").count();
  await p.getByRole("button", { name: "일기 보기" }).click();
  await p.waitForTimeout(500);
  r.reopened = await p.getByLabel("일기 내용").inputValue();
  await p.getByLabel("일기 내용").fill("");
  await p.getByRole("button", { name: "오늘의 기분 🥳, 바꾸기" }).click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "기분 지우기" }).click();
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(400);
  r.removedWhenEmpty = await p.getByRole("button", { name: "일기 쓰기" }).count();
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
