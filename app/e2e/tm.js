const { chromium } = require("playwright");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  await p.getByLabel("11월 3일", { exact: true }).first().click(); // seed data lives on 3 Nov
  await p.getByText("책 30쪽 읽기").click();
  await p.waitForTimeout(500);
  await p.getByText("타이머 열기").click();
  await p.waitForTimeout(600);
  r.idle = await p.getByLabel("기록한 시간 00:00:00").count();
  await p.getByRole("button", { name: "시작하기" }).click();
  await p.waitForTimeout(2300);
  r.running = await p.getByLabel(/기록한 시간 00:00:0[2-3]/).count();
  await p.screenshot({ path: "S08.png" });
  await p.getByRole("button", { name: "일시정지" }).click();
  await p.waitForTimeout(1200);
  r.pausedHeld = await p.getByLabel(/기록한 시간 00:00:0[2-3]/).count();
  r.resumeLabel = await p.getByRole("button", { name: "이어서 하기" }).count();
  await p.reload({ waitUntil: "networkidle" });
  await p.waitForTimeout(800);
  r.afterReload = await p.getByLabel(/기록한 시간 00:00:0[2-3]/).count();
  await p.goto(p.url().replace("/timer/", "/todo/"), { waitUntil: "networkidle" });
  await p.waitForTimeout(600);
  r.info = await p.getByText(/기록한 시간 [23]초/).count();
  r.infoMemo = await p.getByText("에세이 - 3장").count();
  await p.screenshot({ path: "S05b.png" });
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
