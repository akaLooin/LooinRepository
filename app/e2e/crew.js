// 크루 (demo crews): the row in 둘러보기, a crew page with the ranking, 참가 신청 (message + category) → 참가 신청 중 →
// cancel, 크루란? guide, search finds crews, 만들기 → my own crew with the leader's menu.
const { chromium } = require("playwright");
const out = process.argv[2] || ".";
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 411, height: 891 } });
  const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  const r = {};
  await p.goto("http://localhost:8765/", { waitUntil: "networkidle" });
  await p.evaluate(() => localStorage.clear()); await p.reload({ waitUntil: "networkidle" });
  await p.waitForTimeout(500);
  await p.getByRole("tab", { name: "둘러보기" }).click();
  await p.waitForTimeout(800);
  r.row = await p.getByRole("heading", { name: "크루" }).count();
  r.card = await p.getByRole("button", { name: /^아침 운동 모임 크루/ }).count();
  await p.screenshot({ path: `${out}/crew-row.png` });
  await p.getByRole("button", { name: /^아침 운동 모임 크루/ }).click();
  await p.waitForTimeout(800);
  r.title = await p.getByRole("heading", { name: "아침 운동 모임" }).count();
  r.ranking = await p.getByText("에서 9개의 할 일을 완료", { exact: false }).count();
  r.medal = await p.getByLabel("1등").count();
  r.crown = await p.getByRole("button", { name: "토끼, 크루장" }).count();
  r.noTodayForStrangers = await p.getByLabel(/의 오늘 할 일$/).count() === 0;
  await p.screenshot({ path: `${out}/crew-page.png` });
  // apply
  await p.getByRole("button", { name: "참가 신청하기" }).click();
  await p.waitForTimeout(600);
  await p.getByLabel("크루에 보낼 메시지").fill("같이 운동해요!");
  await p.getByRole("button", { name: "크루에 공유할 카테고리 선택" }).click();
  await p.waitForTimeout(400);
  await p.getByRole("radio", { name: "To Do" }).click();
  await p.getByRole("button", { name: "확인" }).last().click();
  await p.waitForTimeout(300);
  r.categoryChosen = await p.getByRole("button", { name: "공유할 카테고리 To Do, 바꾸기" }).count();
  await p.screenshot({ path: `${out}/crew-apply.png` });
  await p.getByRole("button", { name: "확인" }).first().click();
  await p.waitForTimeout(900);
  r.pending = await p.getByRole("button", { name: "참가 신청 중" }).count();
  r.toast = await p.getByText("참가 신청을 보냈어요").count();
  await p.getByRole("button", { name: "참가 신청 중" }).click();
  await p.waitForTimeout(300);
  r.askCancel = await p.getByText("참가 신청을 취소하시겠습니까?").count();
  await p.getByRole("button", { name: "삭제" }).click();
  await p.waitForTimeout(700);
  r.cancelled = await p.getByRole("button", { name: "참가 신청하기" }).count();
  // guide and search
  await p.getByRole("button", { name: "뒤로 가기" }).click();
  await p.waitForTimeout(500);
  await p.getByRole("button", { name: "크루란?" }).click();
  await p.waitForTimeout(500);
  r.guide = await p.getByRole("heading", { name: "크루 가이드" }).count();
  await p.getByRole("button", { name: /^2\. / }).click();
  await p.waitForTimeout(200);
  r.faqOpen = await p.getByText("공개 설정과 관계없이", { exact: false }).count();
  await p.getByRole("button", { name: "뒤로 가기" }).click();
  await p.waitForTimeout(500);
  await p.getByLabel("계정 또는 크루 찾기").fill("독서");
  await p.waitForTimeout(800);
  r.searchCrew = await p.getByRole("button", { name: /^하루 한 장 독서 크루/ }).count();
  await p.getByLabel("계정 또는 크루 찾기").fill("");
  await p.waitForTimeout(500);
  // make my own crew
  await p.getByRole("button", { name: "만들기" }).click();
  await p.waitForTimeout(500);
  await p.getByLabel("크루 이름").fill("물 마시기 크루");
  await p.getByLabel("크루 소개").fill("하루 2L!");
  await p.getByRole("button", { name: "크루에 공유할 카테고리 선택" }).click();
  await p.waitForTimeout(400);
  await p.getByRole("radio", { name: "To Do" }).click();
  await p.getByRole("button", { name: "확인" }).last().click();
  await p.waitForTimeout(300);
  await p.getByRole("button", { name: "완료" }).click();
  await p.waitForTimeout(900);
  r.mine = await p.getByRole("heading", { name: "물 마시기 크루" }).count();
  r.leaderMenu = await p.getByRole("button", { name: "크루 메뉴" }).count();
  r.myToday = await p.getByLabel(/의 오늘 할 일$/).count();
  await p.screenshot({ path: `${out}/crew-mine.png` });
  r.errors = errs;
  console.log(JSON.stringify(r, null, 1));
  await b.close();
})();
